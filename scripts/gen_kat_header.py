#!/usr/bin/env python3
"""
Generate lwc_kat_vectors.h for the firmware from vectors/:
  - vectors/simon64_128.json, vectors/present80.json
  - every vector of vectors/official/asconaead128_LWC_AEAD_KAT_128_128.txt

Usage: gen_kat_header.py <output.h>
"""

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "host"))
from lwc_host import OFFICIAL_ASCON_KAT, VECTORS_DIR, parse_lwc_kat  # noqa: E402


def c_bytes(data, indent="    "):
    hexes = [f"0x{b:02x}" for b in data]
    return "\n".join(indent + ", ".join(hexes[i:i + 16]) + "," for i in range(0, len(hexes), 16))


def block_table(name, path):
    vectors = json.loads(path.read_text())["vectors"]
    rows = []
    for v in vectors:
        key = bytes.fromhex(v["key"]).ljust(16, b"\0")
        pt, ct = bytes.fromhex(v["plaintext"]), bytes.fromhex(v["ciphertext"])
        rows.append("    {{%s}, {%s}, {%s}}," % tuple(", ".join(f"0x{b:02x}" for b in x) for x in (key, pt, ct)))
    return (f"#define LWC_KAT_{name.upper()}_COUNT {len(vectors)}\n"
            f"static const lwc_kat_block_t lwc_kat_{name}[] = {{\n" + "\n".join(rows) + "\n};\n")


def main():
    out = Path(sys.argv[1])
    vectors = parse_lwc_kat(OFFICIAL_ASCON_KAT)
    blob, index, max_pt = bytearray(), [], 0
    for v in vectors:
        pt_len = len(v["pt"])
        assert pt_len < 256 and len(v["ad"]) < 256 and len(v["ct"]) == pt_len + 16
        index.append(f"    {{{len(blob)}u, {pt_len}u, {len(v['ad'])}u}},")
        blob += v["key"] + v["nonce"] + v["ad"] + v["pt"] + v["ct"]
        max_pt = max(max_pt, pt_len)

    text = f"""/* GENERATED by scripts/gen_kat_header.py from vectors/ -- do not edit. */
#ifndef LWC_KAT_VECTORS_H
#define LWC_KAT_VECTORS_H

#include <stdint.h>

typedef struct {{ uint8_t key[16]; uint8_t pt[8]; uint8_t ct[8]; }} lwc_kat_block_t;
/* Ascon: blob[off..] = key[16] nonce[16] ad[ad_len] pt[pt_len] ct[pt_len] tag[16] */
typedef struct {{ uint32_t off; uint8_t pt_len; uint8_t ad_len; }} lwc_kat_ascon_t;

{block_table("simon", VECTORS_DIR / "simon64_128.json")}
{block_table("present", VECTORS_DIR / "present80.json")}
#define LWC_KAT_ASCON_COUNT {len(vectors)}
#define LWC_KAT_ASCON_MAX_PT {max(max_pt, 1)}
static const lwc_kat_ascon_t lwc_kat_ascon[] = {{
{chr(10).join(index)}
}};
static const uint8_t lwc_kat_ascon_blob[] = {{
{c_bytes(blob)}
}};

#endif /* LWC_KAT_VECTORS_H */
"""
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, newline="\n")
    print(f"wrote {out} ({len(vectors)} Ascon vectors, {len(blob)} bytes)")


if __name__ == "__main__":
    main()
